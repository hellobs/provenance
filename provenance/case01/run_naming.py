# -*- coding: utf-8 -*-
"""实跑记录的命名:一次运行一个名字,名字里带**真实日期时刻**。

为什么单独一个模块
------------------
驱动侧(`case01.vizkit.live_run`)与运维入口(`live_switch.py`)都要生成这个名字。
live_run 顶层 import 了 mavis_vizkit(较重),而 `live_switch.py --status` 只是看进程,
不该被拖着一起 import——所以把这一行命名逻辑放在无依赖的叶子模块里,两边共用一份实现。

为什么名字必须带时间
--------------------
1. **一次运行一个身份**:旧默认是 `live-<分支>`(不带时间),同一分支跑第二次就没法与
   上一次区分,也看不出哪条是哪次跑的(2026-09-19 指出)。
2. **真实运行时间唯一的落点**:原始记录与成品记录里只有**模拟剧情日期**
   (如 2026-08-27 → 2026-09-15),没有墙上时钟字段。所以"这次是什么时候跑的"
   只能由名字承载。
3. 名字与落盘目录同名,按名字排序即按时间排序。

注意区分两种日期(别混):
- **名字里的** = 真实运行时间(`live-B-20260919-1424` → 2026-09-19 14:24 跑的);
- **记录里的** `start_date`/`end_date` = 模拟剧情日期(案例内部的时间线)。
"""
import time


def run_id_for(branch: str, when: str = "") -> str:
    """生成 `live-<分支>-<YYYYMMDD-HHMM>`。

    when: 便于测试注入固定时刻;留空用当前本地时间。
    """
    stamp = when or time.strftime("%Y%m%d-%H%M")
    return "live-{}-{}".format(branch, stamp)
